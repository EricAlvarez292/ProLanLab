        System.out.println("+-------------------------------------------+");
        System.out.println("|     # Breadth-First Search (BFS)        |");
        System.out.println("|     def bfs(self, start):               |");
        System.out.println("|         visited = set()                 |");
        System.out.println("|         queue = [start]                 |");
        System.out.println("|         result = []                     |");
