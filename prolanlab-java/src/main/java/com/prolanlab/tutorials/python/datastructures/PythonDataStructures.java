        System.out.println("|                 return                  |");
        System.out.println("|         bucket.append((key, value))    |");
        System.out.println("|                                         |");
        System.out.println("|     def get(self, key):                 |");
        System.out.println("|         hash_key = self._hash(key)      |");
        System.out.println("|         bucket = self.table[hash_key]   |");
        System.out.println("|         for k, v in bucket:             |");
        System.out.println("|             if k == key:                |");
        System.out.println("|                 return v                |");
        System.out.println("|         raise KeyError(key)             |");
