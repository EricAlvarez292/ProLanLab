    /**
     * Demonstrates Python encapsulation and access control
     */
    public void showPythonEncapsulation() {
        System.out.println("\n" + "=".repeat(75));
        System.out.println(">> PYTHON ENCAPSULATION");
        System.out.println("=".repeat(75));
        System.out.println();
        System.out.println("Encapsulation hides internal implementation details.");
        System.out.println();
        System.out.println("1. PRIVATE ATTRIBUTES:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class BankAccount:                      |");
        System.out.println("|     def __init__(self, initial_balance): |");
        System.out.println("|         # Public attribute              |");
        System.out.println("|         self.account_holder = 'User'    |");
        System.out.println("| \t\t\t                                         |");
        System.out.println("|         # Protected attribute (convention) |");
        System.out.println("|         self._account_number = 'ACC123'  |");
        System.out.println("|                                         |");
        System.out.println("|         # Private attribute (name mangling) |");
        System.out.println("|         self.__balance = initial_balance |");
        System.out.println("|                                         |");
        System.out.println("|     def get_balance(self):  # Public method |");
        System.out.println("|         return self.__balance           |");
        System.out.println("|                                         |");
        System.out.println("|     def deposit(self, amount):          |");
        System.out.println("|         if self.__validate_amount(amount): |");
        System.out.println("|             self.__balance += amount    |");
        System.out.println("|                                         |");
        System.out.println("|     def __validate_amount(self, amount): # Private method |");
        System.out.println("|         return amount > 0               |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("2. ACCESS CONTROL:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| account = BankAccount(1000)             |");
        System.out.println("|                                         |");
        System.out.println("| # Public access - works                 |");
        System.out.println("| print(account.account_holder)  # 'User' |");
        System.out.println("|                                         |");
        System.out.println("| # Protected access - works but discouraged |");
        System.out.println("| print(account._account_number)  # 'ACC123' |");
        System.out.println("|                                         |");
        System.out.println("| # Private access - AttributeError       |");
        System.out.println("| # print(account.__balance)  # Error!    |");
        System.out.println("|                                         |");
        System.out.println("| # Access through name mangling (not recommended) |");
        System.out.println("| print(account._BankAccount__balance)  # 1000 |");
        System.out.println("|                                         |");
        System.out.println("| # Proper access through public methods  |");
        System.out.println("| print(account.get_balance())  # 1000    |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("3. GETTERS AND SETTERS:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class Student:                          |");
        System.out.println("|     def __init__(self, name):           |");
        System.out.println("|         self.__name = name              |");
        System.out.println("|         self.__grades = []              |");
        System.out.println("|                                         |");
        System.out.println("|     # Getter methods                    |");
        System.out.println("|     def get_name(self):                 |");
        System.out.println("|         return self.__name              |");
        System.out.println("|                                         |");
        System.out.println("|     def get_grades(self):               |");
        System.out.println("|         return self.__grades.copy()  # Return copy |");
        System.out.println("|                                         |");
        System.out.println("|     # Setter methods with validation    |");
        System.out.println("|     def add_grade(self, grade):         |");
        System.out.println("|         if 0 <= grade <= 100:           |");
        System.out.println("|             self.__grades.append(grade) |");
        System.out.println("|         else:                           |");
        System.out.println("|             raise ValueError('Invalid grade') |");
        System.out.println("|                                         |");
        System.out.println("|     def get_average(self):              |");
        System.out.println("|         if self.__grades:               |");
        System.out.println("|             return sum(self.__grades) / len(self.__grades) |");
        System.out.println("|         return 0                        |");
        System.out.println("+-------------------------------------------+");
    }
    
    /**
     * Explains Python inner classes and their usage
     */
    public void showPythonInnerClasses() {
        System.out.println("\n" + "=".repeat(75));
        System.out.println(">> INNER CLASSES");
        System.out.println("=".repeat(75));
        System.out.println();
        System.out.println("Inner classes are classes defined inside other classes.");
        System.out.println();
        System.out.println("1. BASIC INNER CLASS:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class Computer:                         |");
        System.out.println("|     def __init__(self, brand):          |");
        System.out.println("|         self.brand = brand              |");
        System.out.println("|         self.cpu = self.CPU()           |");
        System.out.println("|         self.gpu = self.GPU()           |");
        System.out.println("|                                         |");
        System.out.println("|     class CPU:  # Inner class           |");
        System.out.println("|         def __init__(self):             |");
        System.out.println("|             self.cores = 4              |");
        System.out.println("|             self.speed = '3.2 GHz'      |");
        System.out.println("|                                         |");
        System.out.println("|         def process(self):              |");
        System.out.println("|             return 'Processing data...' |");
        System.out.println("|                                         |");
        System.out.println("|     class GPU:  # Another inner class   |");
        System.out.println("|         def __init__(self):             |");
        System.out.println("|             self.memory = '8GB'         |");
        System.out.println("|                                         |");
        System.out.println("|         def render(self):               |");
        System.out.println("|             return 'Rendering graphics...' |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("2. ACCESSING INNER CLASSES:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| # Create outer class instance           |");
        System.out.println("| my_computer = Computer('Dell')          |");
        System.out.println("|                                         |");
        System.out.println("| # Access inner class through outer instance |");
        System.out.println("| print(my_computer.cpu.cores)    # 4    |");
        System.out.println("| print(my_computer.cpu.process()) # 'Processing data...' |");
        System.out.println("| print(my_computer.gpu.render())  # 'Rendering graphics...' |");
        System.out.println("|                                         |");
        System.out.println("| # Create inner class directly           |");
        System.out.println("| standalone_cpu = Computer.CPU()         |");
        System.out.println("| print(standalone_cpu.process())         |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("3. INNER CLASS WITH OUTER REFERENCE:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class University:                       |");
        System.out.println("|     def __init__(self, name):           |");
        System.out.println("|         self.name = name                |");
        System.out.println("|         self.students = []              |");
        System.out.println("|                                         |");
        System.out.println("|     def enroll_student(self, student_name): |");
        System.out.println("|         student = self.Student(student_name, self) |");
        System.out.println("|         self.students.append(student)   |");
        System.out.println("|         return student                  |");
        System.out.println("|                                         |");
        System.out.println("|     class Student:                      |");
        System.out.println("|         def __init__(self, name, university): |");
        System.out.println("|             self.name = name            |");
        System.out.println("|             self.university = university # Reference to outer |");
        System.out.println("|             self.courses = []           |");
        System.out.println("|                                         |");
        System.out.println("|         def get_university_info(self):  |");
        System.out.println("|             return f'Student at {self.university.name}' |");
        System.out.println("|                                         |");
        System.out.println("| uni = University('MIT')                 |");
        System.out.println("| student = uni.enroll_student('Alice')   |");
        System.out.println("| print(student.get_university_info())  # 'Student at MIT' |");
        System.out.println("+-------------------------------------------+");
    }
