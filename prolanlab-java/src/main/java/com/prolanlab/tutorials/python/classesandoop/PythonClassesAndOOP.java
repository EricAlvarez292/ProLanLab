        System.out.println();
        System.out.println("1. METHOD OVERRIDING POLYMORPHISM:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class Shape:                            |");
        System.out.println("|     def area(self):                     |");
        System.out.println("|         raise NotImplementedError('Subclass must implement') |");
        System.out.println("|                                         |");
        System.out.println("|     def perimeter(self):                |");
        System.out.println("|         raise NotImplementedError('Subclass must implement') |");
        System.out.println("|                                         |");
        System.out.println("| class Rectangle(Shape):                 |");
        System.out.println("|     def __init__(self, width, height):  |");
        System.out.println("|         self.width = width              |");
        System.out.println("|         self.height = height            |");
        System.out.println("|                                         |");
        System.out.println("|     def area(self):                     |");
        System.out.println("|         return self.width * self.height |");
        System.out.println("|                                         |");
        System.out.println("|     def perimeter(self):                |");
        System.out.println("|         return 2 * (self.width + self.height) |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("2. POLYMORPHIC BEHAVIOR:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| class Circle(Shape):                    |");
        System.out.println("|     def __init__(self, radius):         |");
        System.out.println("|         self.radius = radius            |");
        System.out.println("|                                         |");
        System.out.println("|     def area(self):                     |");
        System.out.println("|         return 3.14159 * self.radius ** 2 |");
        System.out.println("|                                         |");
        System.out.println("|     def perimeter(self):                |");
        System.out.println("|         return 2 * 3.14159 * self.radius |");
        System.out.println("|                                         |");
        System.out.println("| # Polymorphic function                  |");
        System.out.println("| def describe_shape(shape):              |");
        System.out.println("|     print(f'Area: {shape.area():.2f}')  |");
        System.out.println("|     print(f'Perimeter: {shape.perimeter():.2f}') |");
        System.out.println("|                                         |");
        System.out.println("| # Same function works with different shapes |");
        System.out.println("| rectangle = Rectangle(5, 3)             |");
        System.out.println("| circle = Circle(4)                      |");
        System.out.println("| describe_shape(rectangle)  # Uses Rectangle methods |");
        System.out.println("| describe_shape(circle)     # Uses Circle methods |");
        System.out.println("+-------------------------------------------+");
        System.out.println();
        System.out.println("3. DUCK TYPING:");
        System.out.println("+-------------------------------------------+");
        System.out.println("| # If it walks like a duck and quacks    |");
        System.out.println("| # like a duck, then it is a duck        |");
        System.out.println("|                                         |");
        System.out.println("| class FileWriter:                       |");
        System.out.println("|     def write(self, text):              |");
        System.out.println("|         with open('file.txt', 'w') as f: |");
        System.out.println("|             f.write(text)               |");
        System.out.println("|                                         |");
